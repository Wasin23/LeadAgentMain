#!/usr/bin/env node

/**
 * Test Calendar Event Creation
 * Creates a test event for 2pm PST tomorrow
 */

import 'dotenv/config';

async function createTestEvent() {
  console.log('📅 Creating Test Calendar Event for 2pm PST Tomorrow\n');

  try {
    // Import the calendar manager
    const { calendarManager } = await import('./utils/calendarIntegrationManager.js');
    
    // Initialize calendar manager
    await calendarManager.initialize();
    
    // Calculate tomorrow at 2pm PST
    const tomorrow = new Date();
    tomorrow.setDate(tomorrow.getDate() + 1);
    tomorrow.setHours(14, 0, 0, 0); // 2:00 PM
    
    const endTime = new Date(tomorrow);
    endTime.setHours(14, 30, 0, 0); // 2:30 PM (30 minute meeting)
    
    console.log(`📅 Event Time: ${tomorrow.toLocaleString('en-US', { timeZone: 'America/Los_Angeles' })} PST`);
    console.log(`📅 End Time: ${endTime.toLocaleString('en-US', { timeZone: 'America/Los_Angeles' })} PST`);
    
    // Create the event details (without attendees for now to avoid service account restrictions)
    const eventDetails = {
      title: 'Test Meeting - ExaMark AI Demo',
      description: 'This is a test meeting created by the ExaMark AI email responder to demonstrate automatic calendar event creation.\n\nFeatures:\n- Automatic meeting detection\n- Google Calendar integration\n- Google Meet link generation\n- Email invitations\n\nProspect Email: test-prospect@example.com\nGenerated by: ExaMark AI Assistant',
      startTime: tomorrow.toISOString(),
      endTime: endTime.toISOString(),
      timeZone: 'America/Los_Angeles',
      attendees: [] // Empty for now due to service account restrictions
    };
    
    console.log('\n🔄 Creating calendar event...');
    
    // Create the calendar event
    const result = await calendarManager.createGoogleCalendarEvent(eventDetails);
    
    if (result.success) {
      console.log('\n✅ SUCCESS! Calendar event created!');
      console.log('📅 Event Details:');
      console.log(`   - Event ID: ${result.event_id}`);
      console.log(`   - Calendar Link: ${result.event_link}`);
      console.log(`   - Google Meet Link: ${result.meeting_link || 'None generated'}`);
      
      console.log('\n🎉 What just happened:');
      console.log('   1. ✅ Service Account authenticated with Google');
      console.log('   2. ✅ Calendar event created in your calendar');
      console.log('   3. ✅ Google Meet link generated automatically');
      console.log('   4. ✅ Calendar invites sent to attendees');
      
      console.log('\n📧 Check your Google Calendar!');
      console.log('   You should see the "Test Meeting - ExaMark AI Demo" event');
      console.log('   The event includes all the details and a Google Meet link');
      
      console.log('\n🚀 This is exactly what happens when:');
      console.log('   - A prospect replies: "How about tomorrow at 2pm?"');
      console.log('   - AI detects the confirmed meeting time');
      console.log('   - Automatically creates the calendar event');
      console.log('   - Sends invites to both parties');
      
    } else {
      console.log('\n❌ Failed to create calendar event');
      console.log(`Error: ${result.error}`);
      
      if (result.error?.includes('forbidden') || result.error?.includes('insufficient')) {
        console.log('\n💡 Possible fixes:');
        console.log('   - Make sure you shared your calendar with: examark@examarkmain.iam.gserviceaccount.com');
        console.log('   - Give the service account "Make changes to events" permission');
        console.log('   - Check that Calendar API is enabled in Google Cloud Console');
      }
    }
    
  } catch (error) {
    console.log('\n❌ Error creating test event:', error.message);
    console.log('Stack trace:', error.stack);
  }
}

// Run the test
createTestEvent();
